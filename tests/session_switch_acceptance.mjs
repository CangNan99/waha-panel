import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)('playwright');
const browser=await chromium.connectOverCDP(process.env.PANEL_BROWSER_CDP);
const page=browser.contexts()[0].pages()[0];
const base=process.env.PANEL_UI_TEST_URL;
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try{
  await page.setViewportSize({width:1440,height:900});
  await page.goto(base+'/?session=default');
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="support"]').waitFor();
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="support"] .session-display').click();
  await page.waitForURL('**/?session=support',{timeout:3000});
  await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').filter({hasText:'客服测试'}).waitFor();
  assert.equal(await page.locator('#shellSession').inputValue(),'support');
  assert.equal(await page.locator('[data-view-host]:not([hidden])').locator('#chatLink').getAttribute('href'),'/sessions/support/chats');
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="default"] .session-avatar').click();
  await page.waitForURL('**/?session=default');
  await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').filter({hasText:'测试工作区'}).waitFor();
  console.log('PASS card child clicks select the requested session without ancestor reset');
  let delayed=false;
  await page.route('**/api/status?session=default',async route=>{if(!delayed){delayed=true;await new Promise(resolve=>setTimeout(resolve,350));}await route.continue();});
  await page.locator('[data-view-host]:not([hidden])').locator('#refreshButton').click();
  await page.route('**/api/ui/view?view=dashboard&session=support',async route=>{await new Promise(resolve=>setTimeout(resolve,600));await route.continue();});
  // A second click on the still-visible A must cancel an unfinished switch to B.
  await page.goto(base+'/?session=default');
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="support"]').click();
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="default"]').click();
  await page.waitForTimeout(900);
  assert.ok(page.url().endsWith('/?session=default'));
  assert.equal(await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').textContent(),'测试工作区');
  await page.unroute('**/api/ui/view?view=dashboard&session=support');
  await page.waitForTimeout(10500);
  assert.equal(await page.locator('#shellSession').inputValue(),'default');
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="support"] .session-avatar').click();
  await page.waitForURL('**/?session=support');
  await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').filter({hasText:'客服测试'}).waitFor();
  assert.equal(await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').textContent(),'客服测试');
  if(process.env.PANEL_UI_EVIDENCE)await page.screenshot({path:process.env.PANEL_UI_EVIDENCE+'/session-mobile.png'});
  await page.setViewportSize({width:1440,height:900});
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="support"]').click();
  await page.waitForURL('**/?session=support');
  await page.waitForTimeout(500);
  assert.equal(await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').textContent(),'客服测试');
  assert.equal(await page.locator('#shellSession').inputValue(),'support');
  await page.unroute('**/api/status?session=default');
  await page.locator('[data-shell-nav="settings"]').click();
  await page.locator('[data-view-host]:not([hidden])').locator('#persona').waitFor();
  assert.equal(await page.locator('[data-view-host]:not([hidden])').locator('#defaultText').count(),0);
  await page.locator('[data-shell-nav="dashboard"]').click();
  await page.locator('[data-view-host]:not([hidden])').locator('#sessionList button[data-session="default"]').click();
  await page.waitForURL('**/?session=default');
  await page.goBack();
  await page.waitForURL('**/?session=support');
  await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').filter({hasText:'客服测试'}).waitFor();
  await page.goForward();
  await page.waitForURL('**/?session=default');
  await page.locator('[data-view-host]:not([hidden])').locator('#pageTitle').filter({hasText:'测试工作区'}).waitFor();
  await page.locator('[data-view-host]:not([hidden])').locator('#refreshButton').click();
  assert.equal(errors.length,0,errors.join('\n'));
  if(process.env.PANEL_UI_EVIDENCE)await page.screenshot({path:process.env.PANEL_UI_EVIDENCE+'/session-after.png'});
  console.log('PASS delayed refresh, navigation, settings field removal and no page errors');
}finally{await browser.close();}
